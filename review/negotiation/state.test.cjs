'use strict';
const assert = require('node:assert/strict');
const scene = require('../../assets/negotiation-state.js');
const data = new Map([['chief-office-shifts-v2','old personnel save'],['chief-coffee-shift-v1','old coffee save']]);
const store = {getItem:k => data.get(k) ?? null,setItem:(k,v)=>data.set(k,v)};
assert.equal(scene.read(store),null);
let state=scene.choose(null,'chief-desk');
assert.equal(scene.save(store,state),true);
assert.deepEqual(scene.read(store),state);
state=scene.openBox(state);
scene.save(store,state);
state=scene.choose(scene.read(store),'cat-desk');
scene.save(store,state);
assert.deepEqual(scene.read(store),{version:1,layout:'cat-desk',boxOpened:true});
assert.equal(data.get('chief-office-shifts-v2'),'old personnel save');
assert.equal(data.get('chief-coffee-shift-v1'),'old coffee save');
assert.throws(()=>scene.choose(state,'unknown'));
assert.throws(()=>scene.openBox(null));
data.set(scene.KEY,'{broken');assert.equal(scene.read(store),null);
const blocked={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}};
assert.equal(scene.read(blocked),null);assert.equal(scene.save(blocked,state),false);
console.log('PASS: layout changes, box, reload, invalid and blocked storage, old saves');
